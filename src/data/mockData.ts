// Generate 80 seats for Lanka Main Branch
export function generateInitialSeats(): Seat[] {
  const seats: Seat[] = [];
  const rows = ['A', 'B', 'C', 'D'];
  const seatsPerRow = 20;

  rows.forEach((row) => {
    for (let i = 1; i <= seatsPerRow; i++) {
      const seatNo = `${row}${i.toString().padStart(2, '0')}`;
      
      // Match with predefined mock students
      const student = INITIAL_STUDENTS.find(s => s.seatNo === seatNo);
      
      // Mark some additional seats occupied to simulate realistic 48/80 occupancy
      const isRandomOccupied = !student && (i % 2 === 0 || i === 7 || i === 11 || i === 17);
      
      seats.push({
        id: `seat-${seatNo}`,
        seatNumber: seatNo,
        row,
        branchId: 'br-vns-lanka',
        isOccupied: Boolean(student) || isRandomOccupied,
        studentId: student ? student.id : (isRandomOccupied ? `demo-${seatNo}` : undefined),
        studentName: student ? student.name : (isRandomOccupied ? `Student ${seatNo}` : undefined),
        studentFatherName: student ? student.fatherName : (isRandomOccupied ? `Guardian S.` : undefined),
        studentPhoto: student?.photo,
        shift: student ? student.shift : (isRandomOccupied ? (i % 3 === 0 ? 'morning' : i % 3 === 1 ? 'evening' : 'fullday') : undefined),
        hasSocket: true,
        isCorner: i === 1 || i === 20 || i === 10 || i === 11,
      });
    }
  });

  return seats;
}

